--- The type of the tar entry.
---
--- * `"0"` - regular file
--- * `"1"` - hard link to `link`
--- * `"2"` - symbolic link to `link`
--- * `"3"` - character device
--- * `"4"` - block device
--- * `"5"` - directory
--- * `"6"` - FIFO
--- * `"7"` - contiguous file
---
---@alias Tar.FileType "0" | "1" | "2" | "3" | "4" | "5" | "6" | "7" | string

--- [SHARED AND MENU]
