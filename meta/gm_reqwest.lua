--- Request table for `reqwest`, compatible with the one used by `HTTP`.
---
---@class gm_reqwest.Request : garrysmod.http.Request
---@field url garrysmod.http.RequestURL The target url. Raises a Lua error `"invalid url"` if missing or not a valid URL.
---@field method garrysmod.http.RequestMethod | string | nil Request method, case insensitive. Any valid HTTP method is accepted; defaults to `"GET"`, also used when the method is invalid.
---@field parameters table<string, string> | nil KeyValue table sent as a `application/x-www-form-urlencoded` form body. Ignored if `body` is set. Pairs with non-string keys or values are skipped.
---@field headers table<string, string> | nil KeyValue table for headers. Pairs with non-string keys or values are skipped. If no `User-Agent` is given, `"Valve/Steam HTTP Client 1.0 (4000)"` is sent to mimic `HTTP`.
---@field body string | nil Raw request body, may contain binary data. If set, will **override parameters**.
---@field type string | nil Value of the `Content-Type` header. Always sent; defaults to `"text/plain; charset=utf-8"`.
---@field timeout integer | nil The timeout for the whole request in seconds. Truncated to an integer; values `<= 0` use the default of `60`.
---@field blocking boolean | nil If `true`, the request blocks the main thread until it finishes and `reqwest` returns the result directly. Callbacks are still called before it returns. **Use with care** and choose a short `timeout`, otherwise a hanging request will freeze the server.
---@field success nil | fun( status_code: integer, body: string, headers: table<string, string> ) Called when a response is received (with any status code). Header names are lowercase; repeated headers keep only the last value. Errors thrown inside are silently ignored.
---@field failed nil | fun( reason: "unsuccessful", reason_ext: string ) Called when the request could not be completed (connection, TLS, timeout, etc.). `reason` is always `"unsuccessful"` like in `HTTP`; `reason_ext` is the detailed error message from reqwest. Errors thrown inside are silently ignored.

--- [SHARED AND MENU]
---
--- Drop-in replacement for `HTTP` from the [gmsv_reqwest](https://github.com/WilliamVenner/gmsv_reqwest) binary module, built on Rust's `reqwest`, `tokio` and `rustls`.
---
--- Available after `require( "reqwest" )`. Custom root certificates can be placed in `garrysmod/tls_certificates/client` as `.pem` or `.der` files.
---
--- **Non-blocking** (default): the request is sent on a worker thread and callbacks are called from a `"reqwest"` timer on the main thread. Returns nothing.
---
--- **Blocking** (`blocking = true`): returns the result directly:
---
--- | Result | Returns |
--- |:-------|:--------|
--- | Response received | `true, status_code, body, headers` |
--- | Request failed | `false, "unsuccessful", reason_ext` |
---
--- If `request` is not a table, nothing happens and nothing is returned.
---
--- ```lua
--- reqwest( {
---     url = "https://example.com",
---     success = function( status_code, body, headers ) print( status_code, #body ) end,
---     failed = function( reason, reason_ext ) print( reason_ext ) end
--- } )
---
--- local success, status_code, body = reqwest( { url = "https://example.com", blocking = true, timeout = 5 } )
--- ```
---
--- [View documents](https://github.com/WilliamVenner/gmsv_reqwest)
---
---@param request gm_reqwest.Request
---@return boolean | nil success `true` if a response was received, `false` if the request failed, `nil` if not blocking.
---@return integer | "unsuccessful" | nil status_code The HTTP status code on success, `"unsuccessful"` on failure.
---@return string | nil body The response body on success, the detailed error message on failure.
---@return table<string, string> | nil headers The response headers (lowercase names) on success.
function reqwest( request ) end
